/* `node scripts/icons3d.mjs` — writes src/lib/icons3d.ts, the static require() map Metro needs for the 3D icons in
   assets/icons3d/<finish>/ (stills) and assets/icons3d/<finish>/animated/ (loops). Render them first with
   mobile/design/icons3d/render.ts. */
import fs from 'node:fs'
import path from 'node:path'

const APP = path.resolve(import.meta.dirname, '..')
const DIR = path.join(APP, 'assets/icons3d')
const list = (d, ext) => (fs.existsSync(d) ? fs.readdirSync(d).filter((f) => f.endsWith(ext)).map((f) => f.slice(0, -ext.length)).sort() : [])
const block = (finish, sub, ext) =>
	list(path.join(DIR, finish, sub), ext).map((n) => `\t\t'${n}': require('../../assets/icons3d/${finish}/${sub ? sub + '/' : ''}${n}${ext}'),`).join('\n')

const out = `/* eslint-disable @typescript-eslint/no-require-imports -- Metro bundles only static require() */
// Generated by scripts/icons3d.mjs — do not edit. The 3D icon set: Phosphor glyphs extruded and rendered by
// mobile/design/icons3d, in two finishes (crimson for light grounds, pearl for dark), still and animated.

const STILL = {
	crimson: {
${block('crimson', '', '.png')}
	},
	pearl: {
${block('pearl', '', '.png')}
	},
} as Record<'crimson' | 'pearl', Record<string, number>>

const ANIMATED = {
	crimson: {
${block('crimson', 'animated', '.webp')}
	},
	pearl: {
${block('pearl', 'animated', '.webp')}
	},
} as Record<'crimson' | 'pearl', Record<string, number>>

/** Some names the app uses differ from Phosphor's. */
const ALIAS: Record<string, string> = { bookmark: 'bookmark-simple', squares: 'squares-four', search: 'compass' }

export function icon3d(name: string, finish: 'crimson' | 'pearl', animated?: boolean): number | undefined {
	const key = ALIAS[name] ?? name
	return (animated ? ANIMATED[finish][key] : undefined) ?? STILL[finish][key]
}
`
fs.writeFileSync(path.join(APP, 'src/lib/icons3d.ts'), out)
console.log('icons3d.ts written')
